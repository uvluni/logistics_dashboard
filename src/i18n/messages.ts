const MESSAGES: Record<Language, Messages> = { he, en, es };

/** The text for a key in a language, with {placeholders} filled in. */
export function message(lang: Language, key: MessageKey, vars?: Record<string, string | number>): string {
  const text = MESSAGES[lang]?.[key] ?? he[key];
  return vars ? text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? '')) : text;
}

